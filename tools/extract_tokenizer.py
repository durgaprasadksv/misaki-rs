"""Emit spaCy's English tokenizer patterns and exceptions as Rust source.

misaki tokenizes with spaCy and then subtokenizes within each spaCy token, and
its word-grouping rule reads the TAG of a spaCy token. So reproducing spaCy's
tokenization is the last thing standing between the port and exact parity: the
cases that still differ are all punctuation runs where spaCy's prefix/suffix
peeling decides whether a mark is its own token or part of the word.

    "17—."            -> one token      "17."              -> 17 + .
    "loathsome!--and"  -> one token      "else—but"         -> else + — + but
    "can;—but"         -> one token      "five-storied"     -> five + - + storied

Three pattern sets and one exception table, taken from the live tokenizer so
they cannot drift from what spaCy actually uses:

  prefix_search / suffix_search  anchored alternations, applied by peeling
  infix_finditer                 splits what survives the peeling
  rules                          1,347 special cases, expanded verbatim

The patterns carry large Unicode character classes (currency, icons), so they
are written as raw strings rather than rebuilt.
"""
import sys

import spacy


def rust_raw(pat: str) -> str:
    """A Rust raw string literal with enough hashes to be unambiguous."""
    n = 1
    while ('"' + "#" * n) in pat:
        n += 1
    h = "#" * n
    return 'r%s"%s"%s' % (h, pat, h)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/spacy_tokenizer_data.rs"
    nlp = spacy.load("en_core_web_sm", enable=["tok2vec", "tagger"])
    tk = nlp.tokenizer

    # the compiled searchers hold the real patterns
    prefix = tk.prefix_search.__self__.pattern
    suffix = tk.suffix_search.__self__.pattern
    infix = tk.infix_finditer.__self__.pattern
    url = tk.url_match.__self__.pattern if tk.url_match else None

    from spacy.symbols import ORTH
    rules = {}
    for k, v in tk.rules.items():
        pieces = [d.get(ORTH) for d in v]
        if all(p is not None for p in pieces):
            rules[k] = pieces

    with open(out, "w", encoding="utf-8") as f:
        f.write('''//! spaCy's English tokenizer patterns and exceptions, generated by
//! `tools/extract_tokenizer.py`. See that script for why this is needed.
//!
//! Taken from the live tokenizer's compiled searchers, so they cannot drift
//! from what spaCy actually uses.

/// Anchored alternation matching a prefix to peel off the front.
pub const PREFIX_PATTERN: &str = %s;

/// Anchored alternation matching a suffix to peel off the end.
pub const SUFFIX_PATTERN: &str = %s;

/// Matches inside what survives the peeling; each match becomes a split point.
pub const INFIX_PATTERN: &str = %s;
''' % (rust_raw(prefix), rust_raw(suffix), rust_raw(infix)))
        if url:
            f.write('''
/// A whole-token URL match, which short-circuits all peeling.
pub const URL_PATTERN: &str = %s;
''' % rust_raw(url))
        f.write('''
/// spaCy's tokenizer exceptions: the key is matched as a whole token, and the
/// value is the pieces it expands to.
pub const EXCEPTIONS: &[(&str, &[&str])] = &[
''')
        for k in sorted(rules):
            ps = ", ".join('"%s"' % p.replace("\\", "\\\\").replace('"', '\\"') for p in rules[k])
            kk = '"%s"' % k.replace("\\", "\\\\").replace('"', '\\"')
            f.write("    (%s, &[%s]),\n" % (kk, ps))
        f.write("];\n")

    print("wrote %s" % out)
    print("  prefix pattern %d chars, suffix %d, infix %d" % (len(prefix), len(suffix), len(infix)))
    print("  %d exceptions" % len(rules))


if __name__ == "__main__":
    main()
